using System.Text.Json.Serialization;

namespace StealAnEggUltimate;

/// <summary>Minimal 3D vector (Roblox world space, studs).</summary>
public readonly struct Vec3
{
    public readonly double X;
    public readonly double Y;
    public readonly double Z;

    public Vec3(double x, double y, double z)
    {
        X = x;
        Y = y;
        Z = z;
    }

    public static Vec3 Zero => new(0, 0, 0);

    public double DistanceTo(in Vec3 other)
    {
        var dx = X - other.X;
        var dy = Y - other.Y;
        var dz = Z - other.Z;
        return Math.Sqrt(dx * dx + dy * dy + dz * dz);
    }

    public Vec3 Lerp(in Vec3 to, double t)
    {
        t = Math.Clamp(t, 0, 1);
        return new Vec3(X + (to.X - X) * t, Y + (to.Y - Y) * t, Z + (to.Z - Z) * t);
    }

    public override string ToString() => $"X {X:0}  Y {Y:0}  Z {Z:0}";
}

public enum EggRarity
{
    Common = 0,
    Uncommon = 1,
    Rare = 2,
    Epic = 3,
    Legendary = 4,
    Mythic = 5
}

public enum EggOrigin
{
    /// <summary>Generated by the built-in deterministic demo world.</summary>
    Demo = 0,
    /// <summary>Reported by the official STEAL AN EGG test place (file bridge or HTTP API).</summary>
    Official = 1,
    /// <summary>Reported by a user-supplied snapshot file (read-only, no game interaction).</summary>
    External = 2
}

/// <summary>A single egg in the hub's world model.</summary>
public sealed class Egg : ObservableObject
{
    private bool _tracked;
    private double _distance;
    private bool _onScreen;
    private double _screenX;
    private double _screenY;
    private double _heading;

    public Egg(string id, string name, EggRarity rarity, int value, Vec3 position, EggOrigin origin = EggOrigin.Demo, string? zone = null)
    {
        Id = id;
        Name = name;
        Rarity = rarity;
        Value = value;
        Position = position;
        SpawnPosition = position;
        Origin = origin;
        Zone = zone ?? "Island";
    }

    public string Id { get; }
    public string Name { get; }
    public EggRarity Rarity { get; }
    public int Value { get; }
    public string Zone { get; }

    public Vec3 Position { get; private set; }
    public Vec3 SpawnPosition { get; }

    public EggOrigin Origin { get; private set; }

    public bool IsRare => Rarity >= EggRarity.Rare;

    public bool Tracked
    {
        get => _tracked;
        set => Set(ref _tracked, value);
    }

    /// <summary>Distance from the tracked player position, in studs.</summary>
    public double Distance
    {
        get => _distance;
        set
        {
            if (Set(ref _distance, value)) Raise(nameof(DistanceText));
        }
    }

    public bool OnScreen
    {
        get => _onScreen;
        set => Set(ref _onScreen, value);
    }

    public double ScreenX
    {
        get => _screenX;
        set => Set(ref _screenX, value);
    }

    public double ScreenY
    {
        get => _screenY;
        set => Set(ref _screenY, value);
    }

    public double Heading
    {
        get => _heading;
        set => Set(ref _heading, value);
    }

    [JsonIgnore] public string RarityText => Rarity.ToString().ToUpperInvariant();
    [JsonIgnore] public string ValueText => $"{Value / 1000.0:0.0}k".Replace(".0k", "k");
    [JsonIgnore] public string DistanceText => $"{Distance:0} studs";
    [JsonIgnore] public string OriginText => Origin switch
    {
        EggOrigin.Demo => "DEMO",
        EggOrigin.Official => "OFFICIAL",
        _ => "SNAPSHOT"
    };
    [JsonIgnore] public string Summary => $"{Name}  ·  {RarityText}  ·  {ValueText}";

    public void MoveTo(Vec3 position, EggRarity? rarity = null, int? value = null, EggOrigin? origin = null)
    {
        Position = position;
        if (origin.HasValue) Origin = origin.Value;
        Raise(nameof(Position));
    }

    public void ResetToSpawn()
    {
        Position = SpawnPosition;
        Raise(nameof(Position));
    }
}

/// <summary>DTO shared by the config snapshots and the Roblox JSON bridge.</summary>
public sealed class EggSnapshot
{
    public string Player { get; set; } = string.Empty;
    public string Place { get; set; } = string.Empty;
    public long Time { get; set; }
    public string Source { get; set; } = "unknown";
    public List<EggSnapshotEntry> Eggs { get; set; } = new();
    public PlayerSnapshot? PlayerState { get; set; }
}

public sealed class EggSnapshotEntry
{
    public string Name { get; set; } = "Egg";
    public string Rarity { get; set; } = "Common";
    public int Value { get; set; } = 10;
    public double X { get; set; }
    public double Y { get; set; }
    public double Z { get; set; }
    public bool Taken { get; set; }

    public EggRarity ParseRarity()
        => Enum.TryParse<EggRarity>(Rarity, true, out var rarity) ? rarity : EggRarity.Common;
}

public sealed class PlayerSnapshot
{
    public string Name { get; set; } = "Player";
    public double X { get; set; }
    public double Y { get; set; }
    public double Z { get; set; }
    public double Health { get; set; } = 100;
    public double MaxHealth { get; set; } = 100;
    public double WalkSpeed { get; set; } = 16;

    public double JumpPower { get; set; } = 50;
    public int Coins { get; set; }
    public string Place { get; set; } = string.Empty;

    /// <summary>Camera yaw in degrees (0 = looking down -Z), written by the Luau bridge.</summary>
    public double Heading { get; set; }

    /// <summary>Camera height above the character, in studs (demo uses 14).</summary>
    public double CameraHeight { get; set; } = 14;
}
